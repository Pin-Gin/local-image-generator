DECLARE
  tablespace_count NUMBER := 0;
  omf_dest VARCHAR2(4000);
  datafile_dir VARCHAR2(4000);
BEGIN
  SELECT COUNT(*)
    INTO tablespace_count
    FROM dba_tablespaces
   WHERE tablespace_name = 'LOCALRAG_DATA';

  IF tablespace_count = 0 THEN
    SELECT value
      INTO omf_dest
      FROM v$parameter
     WHERE name = 'db_create_file_dest';

    IF omf_dest IS NOT NULL THEN
      EXECUTE IMMEDIATE
        'CREATE TABLESPACE LOCALRAG_DATA ' ||
        'DATAFILE SIZE 256M AUTOEXTEND ON NEXT 64M MAXSIZE 4G';
    ELSE
      SELECT SUBSTR(file_name, 1, INSTR(file_name, '/', -1))
        INTO datafile_dir
        FROM dba_data_files
       WHERE tablespace_name = 'SYSTEM'
         AND ROWNUM = 1;

      EXECUTE IMMEDIATE
        'CREATE TABLESPACE LOCALRAG_DATA DATAFILE ''' ||
        REPLACE(datafile_dir, '''', '''''') ||
        'localrag_data01.dbf'' SIZE 256M AUTOEXTEND ON NEXT 64M MAXSIZE 4G';
    END IF;

    DBMS_OUTPUT.PUT_LINE('[ORACLE:TABLESPACE:CREATED] LOCALRAG_DATA');
  ELSE
    DBMS_OUTPUT.PUT_LINE('[ORACLE:TABLESPACE:REUSED] LOCALRAG_DATA');
  END IF;
END;
